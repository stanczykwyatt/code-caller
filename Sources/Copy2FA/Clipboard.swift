import AppKit

/// Puts a code on the clipboard so it stays on this Mac and out of clipboard
/// history, then takes it off again after a short time.
@MainActor
final class Clipboard {
    private var clearTask: Task<Void, Never>?
    private var copiedChangeCount: Int?

    func copy(_ code: String, clearingAfter seconds: Int) {
        let pasteboard = NSPasteboard.general
        // Keeps the code off Universal Clipboard, so it isn't sent to your other devices.
        _ = pasteboard.prepareForNewContents(with: .currentHostOnly)
        let item = NSPasteboardItem()
        item.setString(code, forType: .string)
        // Markers from nspasteboard.org that tell clipboard managers not to save this item.
        for marker in Self.privacyMarkers {
            item.setData(Data(), forType: marker)
        }
        pasteboard.writeObjects([item])
        copiedChangeCount = pasteboard.changeCount

        clearTask?.cancel()
        guard seconds > 0 else { return }
        clearTask = Task {
            try? await Task.sleep(for: .seconds(seconds))
            guard !Task.isCancelled else { return }
            clearIfUnchanged()
        }
    }

    /// Clears the clipboard if it still holds the code, leaving anything copied since alone.
    func clearIfUnchanged() {
        guard let copiedChangeCount, NSPasteboard.general.changeCount == copiedChangeCount else { return }
        NSPasteboard.general.clearContents()
        self.copiedChangeCount = nil
    }

    private static let privacyMarkers: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]
}
